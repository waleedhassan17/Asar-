/**
 * Concatenates every migration plus the seed into one file:
 *
 *   npm run db:bundle   ->   supabase/bundle.sql
 *
 * For when a Postgres connection isn't available — the direct connection
 * host is IPv6-only, corporate networks block 5432, and so on. Open the
 * Supabase SQL editor, paste the whole thing, run it once.
 *
 * The output is generated; edit the files in supabase/migrations/ instead.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const FILES = [
  "supabase/migrations/20260806000100_schema.sql",
  "supabase/migrations/20260806000200_views.sql",
  "supabase/migrations/20260806000300_rls.sql",
  "supabase/migrations/20260806000400_api_functions.sql",
  "supabase/migrations/20260806000500_storage.sql",
  "supabase/migrations/20260806000600_directory.sql",
  "supabase/seed.sql",
];

const banner = (text) =>
  ["", "-".repeat(70), `-- ${text}`, "-".repeat(70), ""].join("\n");

const bundle = [
  "-- =====================================================================",
  "-- Asar — complete database setup, generated by scripts/bundle-sql.mjs",
  "--",
  "-- Paste this into the Supabase SQL editor and run it once. Safe to",
  "-- re-run: everything is create-or-replace / if-not-exists / on-conflict.",
  "--",
  "-- Do not edit this file — edit supabase/migrations/ and regenerate with",
  "--   npm run db:bundle",
  "-- =====================================================================",
  ...FILES.map((file) => banner(file) + readFileSync(resolve(process.cwd(), file), "utf8")),
  "",
  banner("Finally: make yourself an admin"),
  "-- update public.profiles set is_admin = true where email = 'you@example.com';",
  "",
].join("\n");

const out = resolve(process.cwd(), "supabase/bundle.sql");
writeFileSync(out, bundle);

const lines = bundle.split("\n").length;
console.log(`Wrote supabase/bundle.sql (${lines} lines, ${FILES.length} files).`);
console.log("Paste it into the Supabase SQL editor and run once.");
